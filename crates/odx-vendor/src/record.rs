//! The vendor manifest (`.odx/vendor.lock`): what `odx vendor` wrote.
//!
//! Per addon, so the next run can tell content changes from version changes
//! and `odx verify --vendored` can prove the directories are untouched.

use serde::{Deserialize, Serialize};

/// The format version odx writes.
pub const VERSION: u32 = 1;

/// `.odx/vendor.lock`.
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct VendorRecord {
    /// Format version.
    pub version: u32,
    /// Vendored addons, sorted by group and name.
    #[serde(default, rename = "addon")]
    pub addons: Vec<VendoredAddon>,
}

/// One vendored addon.
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct VendoredAddon {
    /// Addon (directory) name.
    pub name: String,
    /// Dependency group, and so directory, it was vendored into.
    pub group: String,
    /// Distribution it came from.
    pub package: String,
    /// Package version, or `git <commit>` for a package from git.
    pub source: String,
    /// `sha256:<hex>` of the wheel, for packages from an index.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub wheel: Option<String>,
    /// The manifest version as shipped.
    pub source_version: String,
    /// The manifest version written (bumped when content changed alone).
    pub written_version: String,
    /// Hash of the shipped content (after excludes, before a bump).
    pub source_content: String,
    /// Hash of the directory as written.
    pub tree: String,
}

impl VendorRecord {
    /// Parse the file.
    ///
    /// # Errors
    ///
    /// When it is not a vendor manifest of a version odx reads.
    pub fn parse(text: &str) -> Result<Self, String> {
        let record: Self = toml::from_str(text).map_err(|e| e.message().to_owned())?;
        if record.version == VERSION {
            Ok(record)
        } else {
            Err(format!(
                "vendor manifest version {} is not supported (expected {VERSION})",
                record.version
            ))
        }
    }

    /// The file text, sorted by group and name.
    pub fn render(&self) -> String {
        let mut sorted = self.clone();
        sorted
            .addons
            .sort_by(|a, b| (&a.group, &a.name).cmp(&(&b.group, &b.name)));
        format!(
            "# Generated by odx vendor. Do not edit or commit.\n{}",
            toml::to_string(&sorted).unwrap_or_default()
        )
    }

    /// The entry of addon `name`, in any group.
    pub fn addon(&self, name: &str) -> Option<&VendoredAddon> {
        self.addons.iter().find(|addon| addon.name == name)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn round_trip() {
        let record = VendorRecord {
            version: VERSION,
            addons: vec![
                VendoredAddon {
                    name: "web_responsive".to_owned(),
                    group: "oca".to_owned(),
                    package: "odoo-addon-web-responsive".to_owned(),
                    source: "17.0.1.1.9".to_owned(),
                    wheel: Some("sha256:aa".to_owned()),
                    source_version: "17.0.1.1.9".to_owned(),
                    written_version: "17.0.1.1.9".to_owned(),
                    source_content: "sha256:bb".to_owned(),
                    tree: "sha256:bb".to_owned(),
                },
                VendoredAddon {
                    name: "base_x".to_owned(),
                    group: "oca".to_owned(),
                    package: "odoo-addon-base-x".to_owned(),
                    source: "git 0123".to_owned(),
                    wheel: None,
                    source_version: "17.0.1.0.0".to_owned(),
                    written_version: "17.0.1.0.1".to_owned(),
                    source_content: "sha256:cc".to_owned(),
                    tree: "sha256:dd".to_owned(),
                },
            ],
        };
        let text = record.render();
        assert!(text.starts_with("# Generated by odx vendor."), "{text}");
        let parsed = VendorRecord::parse(&text).unwrap();
        assert_eq!(parsed.addons[0].name, "base_x");
        assert_eq!(parsed.render(), text);
        assert_eq!(parsed.addon("web_responsive").unwrap().group, "oca");
        assert_eq!(parsed.addon("missing"), None);
        assert!(!text.contains("wheel = \"\""));
        assert_eq!(
            VendorRecord::parse("version = 2").unwrap_err(),
            "vendor manifest version 2 is not supported (expected 1)"
        );
        assert!(VendorRecord::parse("version = 1\nother = 1").is_err());
        assert_eq!(
            VendorRecord::parse("version = 1").unwrap(),
            VendorRecord {
                version: 1,
                addons: Vec::new()
            }
        );
    }
}
