//! Filtering `uv export` output for platforms that install wheels from an
//! index (`generic-wheels`).

use crate::normalize_name;
use crate::provided::ProvidedSet;

/// `text` (the output of `uv export`) without provided packages and Odoo.
///
/// Returns the text and the normalized names left out. Entries keep their
/// hashes and comments.
pub fn filter_export(text: &str, provided: &ProvidedSet) -> (String, Vec<String>) {
    let mut kept = String::new();
    let mut omitted = Vec::new();
    let mut skipping = false;
    for line in text.split_inclusive('\n') {
        let starts_entry = !line.starts_with([' ', '\t', '#']) && !line.trim().is_empty();
        if starts_entry {
            let name = entry_name(line);
            skipping = name
                .as_deref()
                .is_some_and(|name| name == "odoo" || provided.contains(name));
            if skipping {
                omitted.extend(name);
            }
        }
        if !skipping {
            kept.push_str(line);
        }
    }
    omitted.sort();
    omitted.dedup();
    (kept, omitted)
}

/// The normalized distribution name an export entry starts with; `None`
/// for options such as `-e .`.
fn entry_name(line: &str) -> Option<String> {
    let end = line
        .find(|c: char| !(c.is_ascii_alphanumeric() || matches!(c, '-' | '_' | '.')))
        .unwrap_or(line.len());
    let name = line.split_at(end).0;
    (!name.is_empty()).then(|| normalize_name(name))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn provided_entries_are_left_out() {
        let export = "\
# This file was autogenerated by uv via the following command:
#    uv export --frozen
-e .
babel==2.10.3 \\
    --hash=sha256:aa \\
    --hash=sha256:bb
    # via odoo
odoo @ git+https://github.com/OCA/OCB.git@0123
odoo-addon-web-responsive==17.0.1.1.9 \\
    --hash=sha256:cc
requests==2.31.0 ; python_version >= '3.10' \\
    --hash=sha256:dd

";
        let provided = ProvidedSet::parse("set", "Babel==2.10.3\nrequests\n");
        let (kept, omitted) = filter_export(export, &provided);
        assert_eq!(
            kept,
            "\
# This file was autogenerated by uv via the following command:
#    uv export --frozen
-e .
odoo-addon-web-responsive==17.0.1.1.9 \\
    --hash=sha256:cc
"
        );
        assert_eq!(omitted, ["babel", "odoo", "requests"]);
    }
}
