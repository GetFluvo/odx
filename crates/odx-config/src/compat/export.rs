use std::fmt::Write as _;

use crate::schema::{ForgeKind, OdxConfig, Repository};
use crate::{MergeSource, Problem};

const HEADER: &str = "# Generated by `odx export` from pyproject.toml [tool.odx]. Do not edit.\n";

/// Files written by `odx export`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Export {
    /// git-aggregator `repos.yaml`.
    pub repos_yaml: String,
    /// doodba `addons.yaml`; `None` when no repository selects addons.
    pub addons_yaml: Option<String>,
    /// What could not be exported.
    pub warnings: Vec<Problem>,
}

/// Write `repos.yaml` (and `addons.yaml`) from `[tool.odx]`.
///
/// The repository URL becomes remote `origin`; branch merges from other
/// URLs get a remote named after the URL's owner. Output is deterministic.
///
/// ```
/// use odx_config::compat::export;
/// use odx_config::parse_pyproject;
/// use std::path::Path;
///
/// let text = "[tool.odx]\nodoo_version = \"17.0\"\n[[tool.odx.repositories]]\nurl = \"https://github.com/OCA/pos.git\"\nmerges = [{ pr = 1 }]\n";
/// let config = parse_pyproject(text, Path::new("p.toml")).unwrap().unwrap().config;
/// let out = export(&config);
/// assert!(out.repos_yaml.ends_with("./pos:\n  remotes:\n    origin: https://github.com/OCA/pos.git\n  merges:\n    - origin 17.0\n    - origin refs/pull/1/head\n  target: origin 17.0-odx\n"));
/// assert_eq!(out.addons_yaml, None);
/// ```
pub fn export(config: &OdxConfig) -> Export {
    let mut repos_yaml = String::from(HEADER);
    let mut addons_yaml = String::from(HEADER);
    let mut any_addons = false;
    let mut warnings = Vec::new();
    for repo in &config.repositories {
        let name = repo_name(repo);
        let dir = repo.target_dir.as_ref().map_or_else(
            || format!("./{name}"),
            |dir| {
                let dir = dir.to_string_lossy();
                if dir.starts_with('/') || dir.starts_with("./") {
                    dir.into_owned()
                } else {
                    format!("./{dir}")
                }
            },
        );
        let base = repo.base.as_deref().unwrap_or(&config.odoo_version);
        let mut remotes = vec![("origin".to_owned(), repo.url.clone())];
        let mut merges = vec![format!("origin {base}")];
        let gitlab = repo.forge == Some(ForgeKind::Gitlab)
            || repo.url.to_ascii_lowercase().contains("gitlab");
        for merge in &repo.merges {
            match merge.source() {
                Ok(MergeSource::Pr(pr)) if gitlab => {
                    merges.push(format!("origin refs/merge-requests/{pr}/head"));
                }
                Ok(MergeSource::Pr(pr)) => merges.push(format!("origin refs/pull/{pr}/head")),
                Ok(MergeSource::Sha(sha)) => merges.push(format!("origin {sha}")),
                Ok(MergeSource::Branch { branch, remote }) => {
                    let remote = remote
                        .map_or_else(|| "origin".to_owned(), |url| remote_name(&mut remotes, url));
                    merges.push(format!("{remote} {branch}"));
                }
                Err(message) => warnings.push(Problem {
                    key: format!("{dir}: merge"),
                    message,
                }),
            }
        }
        let target = repo
            .target_branch
            .clone()
            .unwrap_or_else(|| format!("{base}-odx"));
        let _ = writeln!(repos_yaml, "{}:", scalar(&dir));
        let _ = writeln!(repos_yaml, "  remotes:");
        for (remote, url) in &remotes {
            let _ = writeln!(repos_yaml, "    {}: {}", scalar(remote), scalar(url));
        }
        let _ = writeln!(repos_yaml, "  merges:");
        for merge in &merges {
            let _ = writeln!(repos_yaml, "    - {}", scalar(merge));
        }
        let _ = writeln!(
            repos_yaml,
            "  target: {}",
            scalar(&format!("origin {target}"))
        );
        if let Some(addons) = &repo.addons {
            any_addons = true;
            let _ = writeln!(addons_yaml, "{}:", scalar(&name));
            for glob in addons {
                let _ = writeln!(addons_yaml, "  - {}", scalar(glob));
            }
        }
    }
    if !config.packages.is_empty() {
        warnings.push(Problem {
            key: "tool.odx.packages".to_owned(),
            message: "packages are not exported yet".to_owned(),
        });
    }
    Export {
        repos_yaml,
        addons_yaml: any_addons.then_some(addons_yaml),
        warnings,
    }
}

/// The repository's name, or the last URL path segment without `.git`.
fn repo_name(repo: &Repository) -> String {
    repo.name.clone().unwrap_or_else(|| {
        let path = repo.url.trim_end_matches('/');
        let last = path.rsplit(['/', ':']).next().unwrap_or(path);
        last.trim_end_matches(".git").to_owned()
    })
}

/// A remote name for `url`: the owner from the URL, made unique.
fn remote_name(remotes: &mut Vec<(String, String)>, url: &str) -> String {
    if let Some((name, _)) = remotes.iter().find(|(_, known)| known == url) {
        return name.clone();
    }
    let segments: Vec<&str> = url
        .trim_end_matches('/')
        .split(['/', ':'])
        .filter(|s| !s.is_empty())
        .collect();
    let owner = segments
        .len()
        .checked_sub(2)
        .and_then(|i| segments.get(i))
        .copied()
        .unwrap_or("remote");
    let mut name = owner.to_owned();
    let mut n = 2;
    while remotes.iter().any(|(known, _)| *known == name) {
        name = format!("{owner}{n}");
        n += 1;
    }
    remotes.push((name.clone(), url.to_owned()));
    name
}

/// A YAML scalar: plain when unambiguous, double-quoted otherwise.
fn scalar(text: &str) -> String {
    let plain = !text.is_empty()
        && text
            .chars()
            .next()
            .is_some_and(|c| c.is_ascii_alphanumeric() || matches!(c, '.' | '/' | '_'))
        && text.chars().all(|c| {
            c.is_ascii_alphanumeric()
                || matches!(c, '.' | '/' | '_' | '-' | '@' | ':' | '+' | ' ' | '*')
        })
        && !text.contains(": ")
        && !text.ends_with(':')
        && !matches!(
            text.to_ascii_lowercase().as_str(),
            "true" | "false" | "yes" | "no" | "on" | "off" | "null" | "~"
        );
    if plain {
        text.to_owned()
    } else {
        format!("\"{}\"", text.replace('\\', "\\\\").replace('"', "\\\""))
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::compat::{import, parse_addons, parse_repos};

    fn config(toml: &str) -> OdxConfig {
        let text = format!("[tool.odx]\nodoo_version = \"17.0\"\n{toml}");
        crate::parse_pyproject(&text, std::path::Path::new("p.toml"))
            .unwrap()
            .unwrap()
            .config
    }

    #[test]
    fn exports_every_merge_form_and_addons() {
        let config = config(
            r#"
[[tool.odx.repositories]]
name = "pos"
url = "https://github.com/OCA/pos.git"
target_dir = "vendor/pos"
base = "17.0"
target_branch = "17.0-agg"
addons = ["pos_*", "true"]
merges = [
  { pr = 123 },
  { sha = "a1b2c3d4" },
  { branch = "fix", remote = "https://github.com/acme/pos.git" },
  { branch = "fix2", remote = "https://github.com/acme/pos.git" },
  { branch = "other", remote = "https://github.com/acme/pos-fork.git" },
  { branch = "local" },
]

[[tool.odx.repositories]]
url = "git@gitlab.example.com:odoo/web.git"
target_dir = "/abs/web"
forge = "gitlab"
merges = [{ pr = 7 }]
"#,
        );
        let out = export(&config);
        assert_eq!(
            out.repos_yaml,
            format!(
                "{HEADER}./vendor/pos:\n  remotes:\n    origin: https://github.com/OCA/pos.git\n    acme: https://github.com/acme/pos.git\n    acme2: https://github.com/acme/pos-fork.git\n  merges:\n    - origin 17.0\n    - origin refs/pull/123/head\n    - origin a1b2c3d4\n    - acme fix\n    - acme fix2\n    - acme2 other\n    - origin local\n  target: origin 17.0-agg\n/abs/web:\n  remotes:\n    origin: git@gitlab.example.com:odoo/web.git\n  merges:\n    - origin 17.0\n    - origin refs/merge-requests/7/head\n  target: origin 17.0-odx\n"
            )
        );
        assert_eq!(
            out.addons_yaml.unwrap(),
            format!("{HEADER}pos:\n  - pos_*\n  - \"true\"\n")
        );
        assert_eq!(out.warnings, []);
    }

    #[test]
    fn round_trips_semantically_through_import() {
        let original = r"
./vendor/pos:
  remotes:
    oca: https://github.com/OCA/pos.git
    acme: https://github.com/acme/pos.git
  merges:
    - oca 17.0
    - oca refs/pull/123/head
    - oca a1b2c3d4
    - acme 17.0-fix
  target: oca 17.0-agg
";
        let addons = parse_addons("pos: [pos_*]\n").unwrap();
        let first = import(&parse_repos(original).unwrap(), Some(&addons));
        let mut cfg = config("");
        cfg.repositories.clone_from(&first.repositories);
        let out = export(&cfg);
        let again = import(
            &parse_repos(&out.repos_yaml).unwrap(),
            Some(&parse_addons(out.addons_yaml.as_deref().unwrap()).unwrap()),
        );
        assert_eq!(again.repositories, first.repositories);
    }

    #[test]
    fn invalid_merges_and_packages_are_reported() {
        let mut config =
            config("[[tool.odx.repositories]]\nurl = \"https://github.com/OCA/pos/\"\n");
        config.repositories[0].merges.push(crate::schema::Merge {
            pr: None,
            sha: None,
            branch: None,
            remote: None,
            on_conflict: None,
            on_head_change: None,
            track_upstream: None,
        });
        config.packages.insert(
            "odoo-addon-x".to_owned(),
            crate::schema::Package {
                repo: Some("OCA/x".to_owned()),
                url: None,
                pr: Some(1),
                branch: None,
                tag: None,
                rev: None,
                subdirectory: None,
                group: None,
            },
        );
        let out = export(&config);
        assert!(out.repos_yaml.contains("./pos:\n"));
        let found: Vec<_> = out.warnings.iter().map(ToString::to_string).collect();
        assert_eq!(
            found,
            [
                "./pos: merge: needs one of `pr`, `sha` or `branch`",
                "tool.odx.packages: packages are not exported yet",
            ]
        );
    }

    #[test]
    fn scalars_are_quoted_when_needed() {
        assert_eq!(scalar("origin 17.0"), "origin 17.0");
        assert_eq!(scalar("https://x/y.git"), "https://x/y.git");
        for (text, quoted) in [
            ("", "\"\""),
            ("#x", "\"#x\""),
            ("a: b", "\"a: b\""),
            ("a:", "\"a:\""),
            ("Yes", "\"Yes\""),
            ("a\"b\\", "\"a\\\"b\\\\\""),
            ("x=y", "\"x=y\""),
        ] {
            assert_eq!(scalar(text), quoted, "{text}");
        }
    }

    #[test]
    fn remote_names_fall_back_for_short_urls() {
        let mut remotes = Vec::new();
        assert_eq!(remote_name(&mut remotes, "repo"), "remote");
    }
}
