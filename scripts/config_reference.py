#!/usr/bin/env python3
"""Generate docs/configuration.md from the `[tool.odx]` schema.

The tables come from crates/odx-config/src/schema.rs: every deserialized
struct is a table, every field a key, and its doc comment the description.
`--check` fails when the committed page differs from what would be written.
"""

from __future__ import annotations

import re
import sys
from dataclasses import dataclass, field
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SCHEMA = ROOT / "crates" / "odx-config" / "src" / "schema.rs"
PAGE = ROOT / "docs" / "configuration.md"

INTRO = """\
# Configuration

odx reads the `[tool.odx]` table of the project's `pyproject.toml`. Only
`odoo_version` is required; every other key has a default. Unknown keys are
errors, so a typo never goes unnoticed. Keys marked *not used yet* are
accepted, so a configuration can name them already, but have no effect.

Durations are written as a number and a unit: `"90s"`, `"15m"`, `"12h"`,
`"7d"`. Paths are relative to the project root.

The settings of the person rather than the project (forge tokens, mirrors,
local clones, the cache location) live in the
[user configuration](user-config.md).

<!-- Generated by scripts/config_reference.py from the schema; do not edit. -->
"""


@dataclass
class Field:
    name: str
    ty: str
    doc: str
    flatten: bool = False


@dataclass
class Item:
    name: str
    kind: str  # "struct" or "enum"
    doc: str
    fields: list[Field] = field(default_factory=list)
    variants: list[tuple[str, str]] = field(default_factory=list)
    rename_all: str | None = None


def kebab(name: str) -> str:
    return re.sub(r"(?<!^)(?=[A-Z])", "-", name).lower()


def join(doc: list[str]) -> str:
    text = " ".join(line.strip() for line in doc).strip()
    return re.sub(r"\s+", " ", text)


def parse(source: str) -> dict[str, Item]:
    source = source.split("#[cfg(test)]")[0]
    items: dict[str, Item] = {}
    doc: list[str] = []
    attrs: list[str] = []
    lines = source.splitlines()
    i = 0
    while i < len(lines):
        line = lines[i].strip()
        i += 1
        if line.startswith("///"):
            doc.append(line[3:])
            continue
        if line.startswith("#["):
            attrs.append(line)
            continue
        match = re.match(r"pub (struct|enum) (\w+)(<[^>]*>)? \{$", line)
        if match and any("Deserialize" in a for a in attrs):
            # The first paragraph; the rest is for the code's readers.
            blank = [n for n, line in enumerate(doc) if not line.strip()]
            first = doc[: blank[0]] if blank else doc
            item = Item(match.group(2), match.group(1), join(first))
            for attr in attrs:
                rename = re.search(r'rename_all = "([^"]+)"', attr)
                if rename:
                    item.rename_all = rename.group(1)
            i = body(lines, i, item)
            items[item.name] = item
        doc, attrs = [], []
    return items


def body(lines: list[str], i: int, item: Item) -> int:
    doc: list[str] = []
    attrs: list[str] = []
    while i < len(lines):
        line = lines[i].strip()
        i += 1
        if line == "}":
            return i
        if line.startswith("///"):
            doc.append(line[3:])
            continue
        if line.startswith("#["):
            attrs.append(line)
            continue
        if item.kind == "struct":
            match = re.match(r"pub (\w+): (.+),$", line)
            if match:
                item.fields.append(
                    Field(
                        match.group(1),
                        match.group(2),
                        join(doc),
                        any("flatten" in a for a in attrs),
                    )
                )
        else:
            match = re.match(r"(\w+),$", line)
            if match:
                name = match.group(1)
                renamed = [
                    re.search(r'rename = "([^"]+)"', a) for a in attrs
                ]
                value = next((r.group(1) for r in renamed if r), None)
                if value is None:
                    value = kebab(name) if item.rename_all == "kebab-case" else name
                item.variants.append((value, join(doc)))
        doc, attrs = [], []
    return i


SCALARS = {
    "String": "string",
    "u16": "integer",
    "u32": "integer",
    "bool": "boolean",
    "PathBuf": "path",
    "Span": "duration",
}


def unwrap(ty: str) -> str:
    match = re.fullmatch(r"Option<(.+)>", ty)
    return match.group(1) if match else ty


def type_name(ty: str, items: dict[str, Item]) -> str:
    ty = unwrap(ty)
    if ty in SCALARS:
        return SCALARS[ty]
    if ty in items and items[ty].kind == "enum":
        return " \\| ".join(f'`"{value}"`' for value, _ in items[ty].variants)
    if re.fullmatch(r"\[String; 2\]", ty):
        return "pair of strings"
    match = re.fullmatch(r"Vec<(.+)>", ty)
    if match:
        inner = match.group(1)
        if inner in items and items[inner].kind == "enum":
            return "list of " + type_name(inner, items)
        return f"list of {plural(type_name(inner, items))}"
    match = re.fullmatch(r"BTreeMap<String, (.+)>", ty)
    if match:
        return f"table of {plural(type_name(match.group(1), items))}"
    raise SystemExit(f"config_reference.py: no name for the type {ty}")


def plural(name: str) -> str:
    if name.startswith(("list of", "table of", "pair of")):
        return name
    return name + "s"


def section(
    items: dict[str, Item], name: str, path: str, heading: str, out: list[str]
) -> None:
    item = items[name]
    rows: list[str] = []
    later: list[tuple[str, str, str]] = []
    for f in item.fields:
        ty = unwrap(f.ty)
        if ty in items and items[ty].kind == "struct":
            later.append((ty, f"{path}.{f.name}", f"[{path}.{f.name}]"))
            continue
        array = re.fullmatch(r"Vec<(\w+)>", ty)
        if array and array.group(1) in items and items[array.group(1)].kind == "struct":
            later.append((array.group(1), f"{path}.{f.name}", f"[[{path}.{f.name}]]"))
            continue
        keyed = re.fullmatch(r"BTreeMap<String, (\w+)>", ty)
        if keyed and keyed.group(1) in items and items[keyed.group(1)].kind == "struct":
            later.append(
                (keyed.group(1), f"{path}.{f.name}.<name>", f"[{path}.{f.name}.<name>]")
            )
            continue
        key = "`<name>`" if f.flatten else f"`{f.name}`"
        rows.append(f"| {key} | {type_name(f.ty, items)} | {f.doc} |")
    out.append(f"## `{heading}`")
    out.append("")
    if item.doc and name != "OdxConfig":
        out.append(clean(item.doc))
        out.append("")
    if rows:
        out.append("| Key | Type | Description |")
        out.append("| --- | --- | --- |")
        out.extend(rows)
        out.append("")
    for child, child_path, child_heading in later:
        section(items, child, child_path, child_heading, out)


def clean(doc: str) -> str:
    """The struct's description without its leading table name."""
    doc = re.sub(r"^`\[[^`]*\]`(\.\w+`)?:?\s*", "", doc)
    doc = re.sub(r"^`\[\[[^`]*\]\]`\.?\s*", "", doc)
    return doc[:1].upper() + doc[1:] if doc else doc


def render() -> str:
    items = parse(SCHEMA.read_text(encoding="utf-8"))
    out = [INTRO]
    section(items, "OdxConfig", "tool.odx", "[tool.odx]", out)
    return "\n".join(out).rstrip() + "\n"


def main() -> int:
    text = render()
    if "--check" in sys.argv[1:]:
        if PAGE.read_text(encoding="utf-8") != text:
            print(
                "docs/configuration.md is stale: run scripts/config_reference.py",
                file=sys.stderr,
            )
            return 1
        return 0
    PAGE.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
